def _fill_templates(templates: list[str], interest: str = "", seed: int | None = None) -> list[str]:
    """填充模板占位符：{兴趣}→interest（空则用「生活里」），{数字}→random.randint(1,99)。

    seed 传入时用独立随机源（便于测试复现），否则用全局 random。
    """
    import random

    rng = random.Random(seed) if seed is not None else random
    fill = interest.strip() if interest and interest.strip() else "生活里"
    filled: list[str] = []
    for t in templates:
        s = t.replace("{兴趣}", fill)
        while "{数字}" in s:
            s = s.replace("{数字}", str(rng.randint(1, 99)), 1)
        filled.append(s)
    return filled


def get_topic_templates(topic: str, interest: str = "") -> list[str]:
    """按知识点取趣味情境模板（规格 13.7.3）。

    键匹配策略：
    1. 精确匹配 TOPIC_TEMPLATES 的键；
    2. 包含匹配（topic 包含键 或 键包含 topic）提升命中率，例如 topic=「分数」
       也能命中键「分数运算」；
    3. 无匹配 → 回退 INTEREST_MATH_CONTEXTS 按兴趣取 contexts（直接遍历，不重复
       get_math_context_for_interest 的单一返回逻辑）；
    4. 仍无 → 返回 []。

    返回的模板中 {兴趣}/{数字} 占位符均已填充，不含任何「{」。
    """
    topic = (topic or "").strip()
    matched_key: str | None = None
    if topic:
        if topic in TOPIC_TEMPLATES:
            matched_key = topic
        else:
            for key in TOPIC_TEMPLATES:
                if key in topic or topic in key:
                    matched_key = key
                    break
    if matched_key:
        return _fill_templates(TOPIC_TEMPLATES[matched_key], interest)
    if interest and interest in INTEREST_MATH_CONTEXTS:
        contexts = INTEREST_MATH_CONTEXTS[interest].get("contexts", [])
        if contexts:
            return list(contexts)
    return []
